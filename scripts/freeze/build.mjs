// Joins the freeze events with the hop-by-hop trace, measures each hack-linked frozen
// address's net token flow inside the window, and writes data/freezes.json.
// Inputs: scripts/freeze/out/freeze-events.json (data/queries/freeze-events.sql) and
// scripts/freeze/out/trace.json (scripts/freeze/trace.mjs).
// Writes data/queries/freeze-window-balances.sql, data/freezes.json, and appends the
// freeze queries to data/metrics.json.
// Run: node scripts/freeze/build.mjs
import { readFileSync, writeFileSync } from "node:fs"

import { runSql } from "./run.mjs"

const FROM = 26300743
const TO = 26322290
const read = (p) => JSON.parse(readFileSync(new URL(p, import.meta.url), "utf8"))
const events = read("./out/freeze-events.json")
// The issuer-token trace (FOCUS=issuer, 8 hops) is the main one. The all-token trace
// stopped at hop 3 but reaches wallets that got only non-issuer tokens.
const traces = [
  { name: "issuer-tokens", ...read("./out/trace.json") },
  { name: "all-tokens", ...read("./out/trace-all.json") },
]
const trace = { nodes: {} }
for (const t of traces)
  for (const [a, n] of Object.entries(t.nodes))
    if (!trace.nodes[a]) trace.nodes[a] = { ...n, trace: t.name, all: t.nodes }
const meta = {
  ...read("../trace/token-meta.json"),
  // PYUSD never moved in the AMPD-21 trace, so token-meta.json lacks it. Decimals from its verified source.
  "0x6c3ea9036406852006290770bedfcaba0e23a0e8": { symbol: "PYUSD", decimals: 6 },
}
const research = read("../trace/addresses.research.json")

const FREEZE_EVENTS = new Set([
  "AddedBlackList",
  "Blacklisted",
  "AccountPaused",
  "BlockPlaced",
  "Freeze",
  "FreezeAddress",
])

function pathTo(addr) {
  const path = []
  let a = addr
  const nodes = trace.nodes[addr].all
  while (nodes[a]?.parent) {
    const p = nodes[a].parent
    path.unshift({
      from: p.from,
      to: a,
      tx_hash: p.tx_hash,
      block_num: p.block_num,
      token_address: p.token,
      token: meta[p.token]?.symbol ?? null,
    })
    a = p.from
  }
  return path
}

// 1. Hack-linked freezes: the frozen address was reached from a Binance seed.
const linked = events.filter((e) => FREEZE_EVENTS.has(e.event) && trace.nodes[e.account])

// 2. Net Transfer flow per (address, token) from the window start to just before the freeze log.
const rows = linked
  .map(
    (e) =>
      `    (evm_encode_hex('0x000000000000000000000000${e.account.slice(2)}'), evm_encode_hex('${e.token_address}'), ${e.block_num}, ${e.log_index})`,
  )
  .join(",\n")
const sql = `-- Net ERC-20 flow into each hack-linked frozen address, from the window start
-- (block ${FROM}) up to the log just before its freeze event. This is a window-only
-- balance: it is the frozen amount only if the address held none of that token before
-- block ${FROM}. A full-history sum from each token's deployment timed out on staging
-- (10-minute query deadline), so the absolute balance waits on a derived dataset.
-- USDT also moves balances without Transfer logs (issue, redeem, destroyBlackFunds).
-- Generated by scripts/freeze/build.mjs from freeze-events.sql and the trace.
WITH frozen AS (
  SELECT * FROM (VALUES
${rows}
  ) AS f(account_topic, token, freeze_block, freeze_log)
),
t AS (
  SELECT block_num, log_index, address AS token, topic1, topic2,
         arrow_cast(evm_decode_log(topic1, topic2, topic3, data, 'Transfer(address indexed from, address indexed to, uint256 value)')['value'], 'Decimal128(38,0)') AS v
  FROM "{{dataset}}".logs
  WHERE _block_num BETWEEN ${FROM} AND ${Math.max(...linked.map((e) => Number(e.block_num)))}
    AND topic0 = evm_topic('Transfer(address indexed from, address indexed to, uint256 value)')
    AND topic3 IS NULL
    AND address IN (SELECT DISTINCT token FROM frozen)
    AND (topic1 IN (SELECT account_topic FROM frozen) OR topic2 IN (SELECT account_topic FROM frozen))
)
SELECT
  '0x' || substr(evm_decode_hex(f.account_topic), 27) AS account,
  evm_decode_hex(f.token) AS token_address,
  f.freeze_block,
  count(t.v) AS transfers,
  arrow_cast(coalesce(sum(CASE WHEN t.topic2 = f.account_topic THEN t.v END), 0)
           - coalesce(sum(CASE WHEN t.topic1 = f.account_topic THEN t.v END), 0), 'Utf8') AS net_raw
FROM frozen AS f
LEFT JOIN t
  ON t.token = f.token
 AND (t.topic1 = f.account_topic OR t.topic2 = f.account_topic)
 AND (t.block_num < f.freeze_block OR (t.block_num = f.freeze_block AND t.log_index < f.freeze_log))
GROUP BY 1, 2, 3
ORDER BY 3
`
writeFileSync(new URL("../../data/queries/freeze-window-balances.sql", import.meta.url), sql)
const { ms, rows: balances } = await runSql(sql)
console.error(JSON.stringify({ query: "freeze-window-balances", ms, rows: balances.length }))

const fmt = (raw, decimals) => {
  if (raw == null) return null
  const neg = raw.startsWith("-")
  const s = (neg ? raw.slice(1) : raw).padStart(decimals + 1, "0")
  const out = `${s.slice(0, -decimals) || "0"}.${s.slice(-decimals)}`.replace(/\.?0+$/, "")
  return (neg ? "-" : "") + out
}

const freezes = linked.map((e) => {
  const m = meta[e.token_address]
  const b = balances.find((r) => r.account === e.account && r.token_address === e.token_address)
  const node = trace.nodes[e.account]
  const seed = node.hop === 0
  return {
    address: e.account,
    token: m.symbol,
    token_address: e.token_address,
    event: e.event,
    freeze_tx: e.tx_hash,
    block_num: Number(e.block_num),
    ts: e.timestamp.replace(".000Z", "Z"),
    amount: e.amount_raw ? fmt(e.amount_raw, m.decimals) : null,
    amount_note: e.amount_raw
      ? "From the event."
      : seed
        ? "Binance seed wallet (the victim). It held funds before the window, so the window flow is not its balance."
        : "The freeze event has no amount. window_net is the net Transfer flow inside the window only; the absolute balance waits on the derived dataset (AMPD-27).",
    window_net: b && !seed ? fmt(b.net_raw, m.decimals) : null,
    window_transfers: b ? Number(b.transfers) : 0,
    hop: node.hop,
    hub: node.hub,
    trace: node.trace,
    path: pathTo(e.account),
  }
})
writeFileSync(new URL("../../data/freezes.json", import.meta.url), JSON.stringify(freezes, null, 2) + "\n")

// 3. Compare with the outside list.
const outside = new Map(research.map((a) => [a.address, a]))
const frozenAll = [...new Set(events.filter((e) => FREEZE_EVENTS.has(e.event)).map((e) => e.account))]
const report = frozenAll.map((a) => ({
  address: a,
  linked: Boolean(trace.nodes[a]),
  hop: trace.nodes[a]?.hop ?? null,
  trace: trace.nodes[a]?.trace ?? null,
  in_outside_list: outside.has(a),
  outside_role: outside.get(a)?.role ?? null,
  events: events.filter((e) => e.account === a).map((e) => `${meta[e.token_address].symbol} ${e.event}`),
}))
writeFileSync(new URL("./out/compare.json", import.meta.url), JSON.stringify(report, null, 2))
for (const r of report) console.log(JSON.stringify(r))

// 4. Metrics.
const metricsPath = new URL("../../data/metrics.json", import.meta.url)
const metrics = JSON.parse(readFileSync(metricsPath, "utf8")).filter((m) => !m.query.startsWith("freeze-"))
const sum = (ms) => ms.reduce((s, m) => s + m.ms, 0)
const issuerMetrics = read("./out/trace-metrics.json")
const allMetrics = read("./out/trace-all-metrics.json")
const freezeEventsMs = Number(process.env.FREEZE_EVENTS_MS)
metrics.push(
  { query: "freeze-events", ms: freezeEventsMs, rows: events.length, blocks: TO - FROM + 1 },
  {
    query: "freeze-trace-issuer-tokens",
    ms: sum(issuerMetrics),
    rows: Object.keys(traces[0].nodes).length,
    blocks: TO - FROM + 1,
    queries: issuerMetrics.length,
    hops: traces[0].hopsDone,
  },
  {
    query: "freeze-trace-all-tokens",
    ms: sum(allMetrics),
    rows: Object.keys(traces[1].nodes).length,
    blocks: TO - FROM + 1,
    queries: allMetrics.length,
    hops: traces[1].hopsDone,
  },
  {
    query: "freeze-window-balances",
    ms,
    rows: balances.length,
    blocks: Math.max(...linked.map((e) => Number(e.block_num))) - FROM + 1,
  },
)
writeFileSync(metricsPath, JSON.stringify(metrics, null, 2) + "\n")
